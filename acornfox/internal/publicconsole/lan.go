package publicconsole

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"net"
	"net/http"
	"strconv"
	"sync"
	"time"
)

// DefaultLANPort is where the console listens on the LAN when opened. The
// loopback console keeps 18800; a second port avoids binding 0.0.0.0 over it.
const DefaultLANPort = 18802

// LANConfig wires LANManager.
type LANConfig struct {
	Store    *FileStore   // lan-console.json in the data directory
	Sessions Sessions     // the console session store
	Console  http.Handler // the native console handler
	Port     int          // 0 => DefaultLANPort
	Host     func() string
	Logger   *slog.Logger

	// Refuse, when set, is asked before the LAN console is opened and returns
	// a non-empty reason when this machine must not open it: a cloud or other
	// public server has no trusted local network, so "LAN" there would be a
	// password page on the internet. nil => always allowed (a desktop).
	// A LAN console that is already open is left alone.
	Refuse func() string
}

// LANManager opens and closes the console on the local network. The LAN
// entry is the relaxed one: the user sets the password in the browser on the
// first visit, a browser can be remembered for 90 days, and only clients
// with a local-network address are served (see lan_gateway.go). A fresh
// install on a local-network server opens it by default (install.sh); cloud
// servers cannot open it. It implements apiserver.LANConsole.
type LANManager struct {
	cfg     LANConfig
	handler http.Handler

	mu  sync.Mutex
	srv *http.Server
}

// NewLANManager returns a manager; call Apply once at startup.
func NewLANManager(cfg LANConfig) *LANManager {
	if cfg.Port == 0 {
		cfg.Port = DefaultLANPort
	}
	if cfg.Logger == nil {
		cfg.Logger = slog.Default()
	}
	return &LANManager{cfg: cfg, handler: NewGateway(GatewayConfig{
		Store: cfg.Store, Sessions: cfg.Sessions, Console: cfg.Console, LAN: true, Logger: cfg.Logger,
	})}
}

// Handler is what the LAN listener serves: the LAN gateway (local-network
// clients only, the password and remembered devices) in front of the
// console. Tests drive it without opening the port.
func (m *LANManager) Handler() http.Handler { return m.handler }

// Apply starts the listener when the LAN console is enabled and stops it
// otherwise.
func (m *LANManager) Apply() error {
	c, err := m.cfg.Store.Load()
	if err != nil {
		return err
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	if c == nil {
		if m.srv != nil {
			ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
			_ = m.srv.Shutdown(ctx)
			cancel()
			m.srv = nil
		}
		return nil
	}
	if m.srv != nil {
		return nil
	}
	ln, err := net.Listen("tcp", net.JoinHostPort("0.0.0.0", strconv.Itoa(m.cfg.Port)))
	if err != nil {
		return fmt.Errorf("局域网控制台监听 %d 端口失败：%w", m.cfg.Port, err)
	}
	srv := &http.Server{Handler: m.handler, ReadHeaderTimeout: 10 * time.Second, MaxHeaderBytes: 64 << 10}
	m.srv = srv
	go func() {
		if err := srv.Serve(ln); err != nil && !errors.Is(err, http.ErrServerClosed) {
			m.cfg.Logger.Error("lan console", "err", err)
		}
	}()
	m.cfg.Logger.Info("lan console listening", "port", m.cfg.Port)
	return nil
}

// Close stops the listener (process shutdown).
func (m *LANManager) Close() {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.srv != nil {
		_ = m.srv.Close()
		m.srv = nil
	}
}

func (m *LANManager) url() string {
	h := ""
	if m.cfg.Host != nil {
		h = m.cfg.Host()
	}
	if h == "" {
		return ""
	}
	return "http://" + net.JoinHostPort(h, strconv.Itoa(m.cfg.Port))
}

// LANStatus is the wire shape of GET /v1/lan-console.
type LANStatus struct {
	Enabled bool   `json:"enabled"`
	URL     string `json:"url,omitempty"` // http://<LAN address>:<port>
	Port    int    `json:"port"`

	// PasswordSet is false while the LAN console is open and nobody has set
	// a password yet: whoever opens it first from the local network sets it.
	PasswordSet bool `json:"password_set"`
	// PasswordSetAt and PasswordSetFrom say when and from which address the
	// password was set in the browser, so the owner can tell it was them.
	// Absent for a password generated by an older version.
	PasswordSetAt   *time.Time `json:"password_set_at,omitempty"`
	PasswordSetFrom string     `json:"password_set_from,omitempty"`
	// GeneratedPassword marks a LAN console opened by an older version, which
	// still logs in with the generated password.
	GeneratedPassword bool `json:"generated_password,omitempty"`
	Devices           int  `json:"devices"` // remembered devices that have not expired
}

// DeviceView is one remembered device as listed to clients (no secrets).
type DeviceView struct {
	ID         string    `json:"id"`
	Name       string    `json:"name"`
	CreatedAt  time.Time `json:"created_at"`
	LastUsedAt time.Time `json:"last_used_at"`
	LastIP     string    `json:"last_ip,omitempty"`
	ExpiresAt  time.Time `json:"expires_at"`
}

func liveDevices(c *Config, now time.Time) []DeviceView {
	out := []DeviceView{}
	for _, d := range c.Devices {
		if now.Before(d.ExpiresAt) {
			out = append(out, DeviceView{ID: d.ID, Name: d.Name, CreatedAt: d.CreatedAt, LastUsedAt: d.LastUsedAt, LastIP: d.LastIP, ExpiresAt: d.ExpiresAt})
		}
	}
	return out
}

// Status implements apiserver.LANConsole.
func (m *LANManager) Status(context.Context) (LANStatus, error) {
	c, err := m.cfg.Store.Load()
	if err != nil {
		return LANStatus{}, err
	}
	st := LANStatus{Enabled: c != nil, Port: m.cfg.Port}
	if c != nil {
		st.URL = m.url()
		st.PasswordSet = c.HasPassword()
		st.PasswordSetAt, st.PasswordSetFrom = c.PasswordSetAt, c.PasswordSetFrom
		st.GeneratedPassword = c.PasswordHash == "" && c.PasswordSHA256 != ""
		st.Devices = len(liveDevices(c, time.Now().UTC()))
	}
	return st, nil
}

// Enable implements apiserver.LANConsole: it opens the LAN console without a
// password (the first visitor from the local network sets one). Enabling
// again changes nothing. reset also clears the password, every session and
// every remembered device, so the next visitor sets a new one. The returned
// password is always empty; it stays in the signature for older clients that
// print it when present. Errors: *Error with code LAN-CONSOLE-01 when this
// machine must not open a LAN console.
func (m *LANManager) Enable(ctx context.Context, reset bool) (LANStatus, string, error) {
	c, err := m.cfg.Store.Load()
	if err != nil {
		return LANStatus{}, "", err
	}
	switch {
	case c == nil:
		if m.cfg.Refuse != nil {
			if why := m.cfg.Refuse(); why != "" {
				return LANStatus{}, "", &Error{Status: http.StatusConflict, Code: "LAN-CONSOLE-01", Message: why}
			}
		}
		if err := m.cfg.Store.Save(&Config{EnabledAt: time.Now().UTC()}); err != nil {
			return LANStatus{}, "", err
		}
	case reset:
		if err := m.cfg.Store.Update(func(c *Config) { c.ClearPassword() }); err != nil {
			return LANStatus{}, "", err
		}
	}
	if err := m.Apply(); err != nil {
		if c == nil {
			_ = m.cfg.Store.Delete()
		}
		return LANStatus{}, "", err
	}
	st, err := m.Status(ctx)
	return st, "", err
}

// ResetPassword clears the password, every session and every remembered
// device of an open LAN console; the next visitor from the local network
// sets a new password. Errors: *Error (409 lan_console_off) when it is closed.
func (m *LANManager) ResetPassword(ctx context.Context) (LANStatus, error) {
	c, err := m.cfg.Store.Load()
	if err != nil {
		return LANStatus{}, err
	}
	if c == nil {
		return LANStatus{}, &Error{Status: http.StatusConflict, Code: "lan_console_off", Message: "局域网控制台没有开启，没有密码可清。开启：acornfox lan-console enable"}
	}
	if err := m.cfg.Store.Update(func(c *Config) { c.ClearPassword() }); err != nil {
		return LANStatus{}, err
	}
	return m.Status(ctx)
}

// Devices lists the remembered devices that have not expired (empty when the
// LAN console is closed).
func (m *LANManager) Devices(context.Context) ([]DeviceView, error) {
	c, err := m.cfg.Store.Load()
	if err != nil {
		return nil, err
	}
	if c == nil {
		return []DeviceView{}, nil
	}
	return liveDevices(c, time.Now().UTC()), nil
}

// RemoveDevice forgets one remembered device and ends its sessions; it
// reports whether the device existed. Removing twice is not an error.
func (m *LANManager) RemoveDevice(_ context.Context, id string) (bool, error) {
	found := false
	err := m.cfg.Store.Update(func(c *Config) { found = c.RemoveDevice(id) })
	return found, err
}

// RemoveDevices forgets every remembered device and ends their sessions; it
// returns how many there were.
func (m *LANManager) RemoveDevices(context.Context) (int, error) {
	n := 0
	err := m.cfg.Store.Update(func(c *Config) {
		ids := make([]string, 0, len(c.Devices))
		for _, d := range c.Devices {
			ids = append(ids, d.ID)
		}
		for _, id := range ids {
			if c.RemoveDevice(id) {
				n++
			}
		}
	})
	return n, err
}

// Disable implements apiserver.LANConsole.
func (m *LANManager) Disable(context.Context) error {
	if err := m.cfg.Store.Delete(); err != nil {
		return err
	}
	return m.Apply()
}
