// macFault builds an entry of the MAC group. The optional last argument is
// NeedsUser. The causes come first, then steps, actions, ask, verify.
func macFault(code, title, level, next, symptom string, args ...any) Fault {
	f := Fault{Code: code, Group: "MAC", Title: title, Level: level, Next: next, Symptoms: []string{symptom}}
	var strs [][]string
	var rest []string
	for _, a := range args {
		switch v := a.(type) {
		case Cause:
			f.Causes = append(f.Causes, v)
		case []string:
			strs = append(strs, v)
		case []Action:
			f.Actions = v
		case string:
			rest = append(rest, v)
		case bool:
			f.NeedsUser = v
		}
	}
	if len(strs) > 0 {
		f.Steps = strs[0]
	}
	if len(rest) > 0 {
		f.Ask = rest[0]
	}
	if len(rest) > 1 {
		f.Verify = rest[1]
	}
	return f
}
