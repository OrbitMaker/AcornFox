// view (gatewayclient.Codes), next is what the user does.
func gw(code, meaning, client, level, next string, causes ...Cause) Fault {
	return Fault{Code: code, Group: "GW", Origin: "gateway", Title: meaning, Level: level,
		Explain:  meaning,
		Next:     next,
		Auto:     client,
		Symptoms: []string{"安装进度、catalog connect 或命令 --json 输出里 gateway_code 是 " + code},
		Causes:   causes,
		Steps:    []string{"看是哪一步报的（安装、连接私有目录、同步）", "sudo acornfox doctor 看下载网关和时钟两项"},
		Actions:  []Action{{Text: "按“下一步”做", Tier: 1}},
		Ask:      "要改系统设置或联系给码的人时",
		Verify:   "再操作时不再出现这个编号",
		Related:  []string{"SETUP-GW-01"},
	}
}

