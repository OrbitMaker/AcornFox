// Package faults is the fault catalog of AcornFox (the single-machine
// edition): every fault code the program, its install scripts and its
// download gateway client can show has one full entry here — what the user
// sees, the possible causes with how to tell them apart, the order to check
// them, what may be done (graded), when to stop and ask the user, how to
// confirm it is fixed and how to undo.
//
// It is the single source for the full entries:
//
//   - `acornfox faults` lists them, `acornfox faults <code>` prints one
//     (--json, --markdown);
//   - GET /v1/faults and GET /v1/faults/{code} serve them; GET
//     /v1/setup/faults serves every entry in the short shape the console's
//     runtime page uses (code, title, causes, next, needs_user);
//   - docs/faults.md is generated by `acornfox faults --markdown` and a test
//     checks it is up to date;
//   - the Skill only tells the reader to run `acornfox faults <code>`.
//
// The packages that raise the codes keep their own short tables
// (appinstall.Faults, setup.Faults, gatewayclient.Codes): they put a hint on
// each error. Tests in this package check that those tables and this catalog
// say the same thing word for word, that every code written anywhere in the
// program, the install scripts, the Skill, the README files, the user docs,
// the release notes and the website is in this catalog, and that every code
// here is raised somewhere (or marked Reserved, or comes from the download
// gateway). `acornfox open` takes its OPEN-APP hints from here.
//
// The tests that read files outside the Go module (docs/faults.md being up
// to date; the codes in the install scripts, the Skill and the docs) skip
// when only the module is present, with a line saying so. Run the tests in a
// full checkout of the repository before merging.
//
// What is in it: the CAT-*, SETUP-*, LAN-CONSOLE-*, INSTALL-*, UPGRADE-*,
// UNINSTALL-*, OPEN-APP-*, ID-KEY-* codes, the download gateway's GW-* codes
// as this machine sees them, and the lower-case diagnosis codes of deploys
// (stage upload … route, addon), of connecting to a server (stage connect),
// of domains and the public console, of the LAN console and of installing
// the Skill. The API's generic error codes (invalid_app, not_found,
// internal, usage, http_<status> when the server gave none …) are not faults
// and are not here: whoever meets one gets the fallback entry ANY-00, whose
// first step is to pass on the error's message and hint.
//
// Rules: a code, once released, is never renamed or reused; new codes are
// appended. A new code needs its entry here in the same change.
package faults

import "strings"

// Cause is one possible cause.
type Cause struct {
	Text  string `json:"text"`
	Check string `json:"check"` // how to tell: a command and what it shows
	Auto  bool   `json:"auto"`  // acornfox doctor tells this one by itself
}

// Action is one thing that may be done. Tier: 0 read-only; 1 may be done
// without asking (deletes no data, spends no money, opens nothing to the
// network, can be undone); 2 only after the user agreed.
type Action struct {
	Text string `json:"text"`
	Tier int    `json:"tier"`
}

// Fault is one catalog entry.
type Fault struct {
	Code  string `json:"code"`
	Group string `json:"group"`
	Title string `json:"title"`
	Level string `json:"level"` // P1 an app or the service is down; P2 a feature does not work; P3 a hint or a usage problem
	// Explain is a longer "what this means" when Title is not enough.
	Explain string `json:"explain,omitempty"`
	// Next is the one-line next step that also travels with the error.
	Next string `json:"next"`
	// Auto is what AcornFox already did about it by itself (fell back to
	// another source, restored the old version …); empty when nothing.
	Auto     string   `json:"auto,omitempty"`
	Symptoms []string `json:"symptoms"`
	Causes   []Cause  `json:"causes"`
	Steps    []string `json:"steps"` // the order to check: read-only and common first
	Actions  []Action `json:"actions"`
	Ask      string   `json:"ask"`    // when to stop and ask the user, and what to bring
	Verify   string   `json:"verify"` // how to confirm it is fixed
	Rollback string   `json:"rollback,omitempty"`
	Related  []string `json:"related,omitempty"`
	// NeedsUser: only the user can clear it (a reboot, an admin
	// confirmation, choosing between keeping and deleting data).
	NeedsUser bool `json:"needs_user"`
	// Stage is the diagnosis stage of a lower-case code (upload, build …).
	Stage string `json:"stage,omitempty"`
	// Origin is "gateway" for a code the download gateway sends; "" for a
	// code AcornFox itself raises.
	Origin string `json:"origin,omitempty"`
	// Reserved: kept for later, nothing raises it yet.
	Reserved bool   `json:"reserved,omitempty"`
	Inject   string `json:"inject,omitempty"` // how to cause it on a test machine; empty: paper drill only
}

// Groups in the order the catalog lists them.
var Groups = []struct{ Key, Name string }{
	{"INSTALL", "安装脚本（install.sh）"},
	{"UPGRADE", "升级和卸载脚本"},
	{"SETUP", "准备运行环境和本机自检（doctor）"},
	{"LAN", "局域网控制台"},
	{"LINK", "连接服务器（diagnosis.stage 为 connect）"},
	{"DEPLOY", "部署诊断（deploy、redeploy、start 等返回的 diagnosis.code）"},
	{"DOMAIN", "域名和公网控制台"},
	{"OPEN", "打开应用"},
	{"CLI", "命令行在这台电脑上的操作（安装 Skill）"},
	{"INST", "应用中心安装（CAT-INST）"},
	{"CONN", "连接私有目录（CAT-CONN）"},
	{"SYNC", "应用目录同步和读取（CAT-SYNC、CAT-LOAD、CAT-PKG）"},
	{"PUB", "打包、签名、检查目录（维护目录的人用：CAT-LINT、CAT-BUILD、CAT-KEY、CAT-VER）"},
	{"GW", "下载网关返回的编号（GW）"},
	{"ID", "本机身份（ID-KEY）"},
	{"ANY", "兜底"},
}

// TierName and LevelName are the names shown next to tiers and levels.
var TierName = map[int]string{0: "只读", 1: "可以直接做", 2: "先问用户"}
var LevelName = map[string]string{"P1": "应用或服务停了，马上处理", "P2": "功能用不了，尽快处理", "P3": "提示或用法问题，不急"}

// Evidence is what to bring whenever an entry says to stop and ask (or to
// report to the maintainers).
const Evidence = "acornfox doctor --json 的输出、出错那条命令加 --json 的完整输出（或安装、升级脚本最后 30 行）、acornfox --json version"

// FallbackCode is the entry Find returns when nothing matches.
const FallbackCode = "ANY-00"

// Catalog is every entry, grouped in the order of Groups, the fallback last.
var Catalog = join(
	installFaults, upgradeFaults, setupFaults, lanFaults, linkFaults, deployFaults, domainFaults, openFaults, cliFaults,
	instFaults, connFaults, syncFaults, pubFaults, gatewayFaults, idFaults, anyFaults,
)

func join(parts ...[]Fault) []Fault {
	var out []Fault
	for _, p := range parts {
		out = append(out, p...)
	}
	return out
}

// Find looks a code up; upper-case codes match in any case. It returns the
// fallback entry and false when the code is not in the catalog.
func Find(code string) (Fault, bool) {
	code = strings.TrimSpace(code)
	for _, try := range []string{code, strings.ToUpper(code), strings.ToLower(code)} {
		for _, f := range Catalog {
			if f.Code == try {
				return f, true
			}
		}
	}
	fb, _ := lookup(FallbackCode)
	return fb, false
}

func lookup(code string) (Fault, bool) {
	for _, f := range Catalog {
		if f.Code == code {
			return f, true
		}
	}
	return Fault{}, false
}

// GroupName returns a group's display name (the key when unknown).
func GroupName(key string) string {
	for _, g := range Groups {
		if g.Key == key {
			return g.Name
		}
	}
	return key
}

// SetupDef is an entry in the short shape of GET /v1/setup/faults (the
// console's runtime page joins check results to it by code).
type SetupDef struct {
	Code      string   `json:"code"`
	Title     string   `json:"title"`
	Causes    []string `json:"causes"`
	Next      string   `json:"next"`
	NeedsUser bool     `json:"needs_user"`
}

// SetupDefs returns every entry in the short shape.
func SetupDefs() []SetupDef {
	out := make([]SetupDef, 0, len(Catalog))
	for _, f := range Catalog {
		causes := make([]string, 0, len(f.Causes))
		for _, c := range f.Causes {
			causes = append(causes, c.Text)
		}
		out = append(out, SetupDef{Code: f.Code, Title: f.Title, Causes: causes, Next: f.Next, NeedsUser: f.NeedsUser})
	}
	return out
}
